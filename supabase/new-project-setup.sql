-- ============================================================
-- 2W Studio — new Supabase project setup
-- Run ONCE in the new project: Supabase Dashboard -> SQL Editor -> New query -> Run
-- ============================================================
-- This creates ONLY what the live website actually uses: the contact form table.
-- The old `waitlist` table is not recreated -- the waitlist form does not exist
-- on the site (its script was never loaded), so nothing writes to it.
-- ============================================================

create table if not exists public.contact_messages (
  id          bigint generated by default as identity primary key,
  created_at  timestamptz not null default now(),
  name        text not null,
  email       text not null,
  message     text
);

-- Row Level Security ON, and deny-by-default.
alter table public.contact_messages enable row level security;

-- The website's anon key may INSERT a message, and nothing else.
drop policy if exists "anon insert contact_messages" on public.contact_messages;
create policy "anon insert contact_messages"
  on public.contact_messages
  for insert
  to anon
  with check (true);

-- NOTE: there is deliberately NO select/update/delete policy for `anon`.
-- With RLS enabled and no SELECT policy, the public key cannot read messages.
-- The previous project allowed `FOR SELECT USING (true)`, which let anyone
-- holding the public key download every submission. Do not recreate that.
--
-- You read submissions in the dashboard (Table Editor), which uses your
-- authenticated session and bypasses these anon policies.

-- Helpful index for sorting newest-first in the dashboard.
create index if not exists idx_contact_messages_created_at
  on public.contact_messages (created_at desc);
